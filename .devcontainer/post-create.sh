#!/bin/bash
# postCreateCommand: install backend + frontend dependencies once per container.
# Runs as the non-root `dev` user.
set -euo pipefail

WORKSPACE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$WORKSPACE"

echo "==> Toolchain"
python --version
node --version
pnpm --version
uv --version
claude --version

# ── Backend ──────────────────────────────────────────────────────────────────
# The venv lives at $VIRTUAL_ENV (/home/dev/.venv, on PATH via the Dockerfile),
# not in the bind-mounted repo, so it never collides with a host venv.
# CPU-only torch comes from UV_EXTRA_INDEX_URL / UV_INDEX_STRATEGY (Dockerfile).
echo "==> Backend dependencies"
if [ ! -x "$VIRTUAL_ENV/bin/python" ]; then
  uv venv --python "$(command -v python)" "$VIRTUAL_ENV"
fi
uv pip install -r backend/requirements.txt
# Test-only deps. backend/requirements-dev.txt wins when it exists (the backend
# CI work adds one); until then install what the test suite imports beyond
# requirements.txt.
if [ -f backend/requirements-dev.txt ]; then
  uv pip install -r backend/requirements-dev.txt
else
  uv pip install "fakeredis==2.40.0"
fi

# Dev-only secrets. Real environment variables (Codespaces secrets, CI env)
# always win over backend/.env in pydantic-settings, so this file is only a
# fallback. It is gitignored, created only when missing, and never rewritten.
if [ ! -f backend/.env ]; then
  echo "==> Generating backend/.env with random dev-only secrets"
  (
    umask 077
    {
      echo "# Generated by .devcontainer/post-create.sh for local development only."
      echo "APP_SECRET_KEY=$(python -c 'import secrets; print(secrets.token_urlsafe(48))')"
      echo "VAULT_ENCRYPTION_KEY=$(python -c 'import secrets; print(secrets.token_hex(32))')"
      echo "JWT_SECRET_KEY=$(python -c 'import secrets; print(secrets.token_urlsafe(48))')"
    } > backend/.env
  )
fi

# ── Frontend ─────────────────────────────────────────────────────────────────
# node_modules is a named volume (docker-compose.yml). Docker creates its mount
# point as root, so hand it to the dev user before installing.
echo "==> Frontend dependencies"
if [ ! -w frontend/node_modules ]; then
  sudo chown "$(id -u):$(id -g)" frontend/node_modules
fi
(cd frontend && pnpm install --frozen-lockfile)

echo "==> post-create done"
